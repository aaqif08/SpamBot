#!/usr/bin/env python
"""Write docs/results.md from the database: every trained model version of an
organisation with its measured hold-out and cross-validation metrics.

    python scripts/report_results.py --email admin@example.com

Only numbers produced by this deployment are written; the research paper's
figures are kept in a clearly separated section for reference.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import _bootstrap  # noqa: F401

_bootstrap.init()

from sqlalchemy import func  # noqa: E402

from app.db.database import SessionLocal  # noqa: E402
from app.db.models import ModelStatus, User  # noqa: E402
from app.services.model_service import ModelService  # noqa: E402
from ml.paper_results import PAPER_REPORTED_RESULTS  # noqa: E402
from ml.train import MODEL_ZOO  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def fmt(v) -> str:  # noqa: ANN001
    return "—" if v is None else f"{float(v):.3f}"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--email", required=True)
    p.add_argument("--out", default=str(ROOT / "docs" / "results.md"))
    args = p.parse_args()
    db = SessionLocal()
    try:
        user = db.query(User).filter(func.lower(User.email) == args.email.lower()).first()
        if user is None:
            print("unknown user", file=sys.stderr)
            return 2
        models = [m for m in ModelService(db).list(user.organization_id) if m.status in (ModelStatus.READY, ModelStatus.PRODUCTION, ModelStatus.DEPRECATED)]
        lines = [
            "# Results generated by this deployment",
            "",
            f"Generated {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC} for organisation `{user.organization.name}` by `scripts/report_results.py`.",
            "",
            "All numbers in section 1 were measured by this deployment (stratified hold-out split; cross-validation on the training split). They are not the research paper's figures, which appear only in section 2.",
            "",
            "## 1. Trained model versions",
            "",
            "| Model | Version | Status | Dataset | Features | Accuracy | Precision | Recall | F1 | ROC-AUC | CV F1 (mean ± std) | Trained |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for m in sorted(models, key=lambda x: (x.algorithm, x.version)):
            t = json.loads(m.test_metrics_json or "{}")
            v = json.loads(m.validation_metrics_json or "{}")
            lines.append(f"| {m.name} | {m.version} | {m.status.value} | {m.dataset_name} | {m.n_features} | {fmt(t.get('accuracy'))} | {fmt(t.get('precision'))} | {fmt(t.get('recall'))} | {fmt(t.get('f1'))} | {fmt(t.get('roc_auc'))} | {fmt((v.get('mean') or {}).get('f1'))} ± {fmt((v.get('std') or {}).get('f1'))} | {m.trained_at:%Y-%m-%d} |" if m.trained_at else "")
        if not models:
            lines.append("| _no trained models_ | | | | | | | | | | | |")
        lines += ["", "## 2. Reported in the research paper (reference only — NOT measured by this deployment)", ""]
        c = PAPER_REPORTED_RESULTS["citation"]
        lines.append(f"{c['title']}, {c['venue']} ({c['year']}), DOI {c['doi']}. 5-fold CV with all 31 features including tweet-derived ones.")
        for kind in ("cresci-15", "cresci-17"):
            block = PAPER_REPORTED_RESULTS["datasets"][kind]
            lines += ["", f"### {kind} ({block['table']})", "", "| Classifier | Accuracy | Precision | Recall | F1 | AUC |", "|---|---|---|---|---|---|"]
            for r in block["results"]:
                lines.append(f"| {MODEL_ZOO[r['algorithm']].display_name} | {fmt(r['accuracy'])} | {fmt(r['precision'])} | {fmt(r['recall'])} | {fmt(r['f1'])} | {fmt(r['roc_auc'])} |")
        Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Wrote {args.out} ({len(models)} models)")
        return 0
    finally:
        db.close()


if __name__ == "__main__":
    sys.exit(main())
